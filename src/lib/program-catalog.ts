import data from "./program-catalog.data.json";

export type ProgramLevelGroup =
  | "foundation"
  | "diploma"
  | "bachelor"
  | "master"
  | "phd"
  | "certificate"
  | "language"
  | "other";

export type ProgramOffering = {
  university: string;
  university_slug: string;
  level: string;
  level_group: ProgramLevelGroup;
  program_slug: string;
  name: string;
  duration: string | null;
  feeTotal: number | null;
  feePerYear: number | null;
  currency: string;
  mqaStatus: string | null;
};

export type CanonicalProgram = {
  slug: string;
  title: string;
  field: string;
  levels: ProgramLevelGroup[];
  offerings: ProgramOffering[];
  universityCount: number;
  feePerYearMin: number | null;
  feePerYearMax: number | null;
  feeTotalMin: number | null;
  feeTotalMax: number | null;
};

// Generated by scripts/build-program-catalog.mjs from public/data/universities.
export const PROGRAM_CATALOG: CanonicalProgram[] = data as CanonicalProgram[];

export const LEVEL_GROUP_ORDER: ProgramLevelGroup[] = [
  "foundation", "diploma", "bachelor", "master", "phd", "certificate", "language", "other",
];

const bySlug = new Map(PROGRAM_CATALOG.map((p) => [p.slug, p]));

const byOffering = new Map<string, CanonicalProgram>();
for (const program of PROGRAM_CATALOG) {
  for (const offering of program.offerings) {
    byOffering.set(`${offering.university_slug}|${offering.level}|${offering.program_slug}`, program);
  }
}

export function getCanonicalProgram(slug: string): CanonicalProgram | null {
  return bySlug.get(slug) ?? null;
}

export function getCanonicalProgramForOffering(
  universitySlug: string,
  level: string,
  programSlug: string
): CanonicalProgram | null {
  return byOffering.get(`${universitySlug}|${level}|${programSlug}`) ?? null;
}

export function sortOfferings(offerings: ProgramOffering[]): ProgramOffering[] {
  const levelRank = (g: ProgramLevelGroup) => {
    const i = LEVEL_GROUP_ORDER.indexOf(g);
    return i === -1 ? LEVEL_GROUP_ORDER.length : i;
  };
  return [...offerings].sort((a, b) => {
    const byLevel = levelRank(a.level_group) - levelRank(b.level_group);
    if (byLevel !== 0) return byLevel;
    const feeA = a.feePerYear ?? a.feeTotal ?? Number.POSITIVE_INFINITY;
    const feeB = b.feePerYear ?? b.feeTotal ?? Number.POSITIVE_INFINITY;
    return feeA - feeB;
  });
}